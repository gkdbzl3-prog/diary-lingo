import { config } from '../config.js';
import { composeSystemPrompt } from '../prompt.js';

export function buildSystemPrompt() {
  const { hardMax } = config.lines.ja;

  return composeSystemPrompt({
    lang: 'ja',
    sections: {
      attach: '요미가나·한글 발음·해석을',

      lines: `## 줄(line) 나누기
각 문장을 의미 덩어리(끊어 읽기 단위)로 여러 줄로 나눕니다. 화면에서 이 줄이 그대로 한 행이 됩니다.
- 문장부호와 절 경계에서 먼저 자릅니다. 문절(文節) 중간에서는 절대 자르지 않습니다.
- 한 줄은 요미가나 기준으로 ${hardMax}자를 넘기면 안 됩니다(공백·문장부호는 세지 않습니다).
- 짧은 문장은 한 줄로 둡니다. 다음 문장과 합치지 않습니다.
- lines의 토큰 w를 전부 이어 붙이면 그 문장의 text와 글자 하나까지 똑같아야 합니다. 공백을 넣지 마세요.`,

      content: `## 토큰
- 문절(文節) 단위로 자릅니다. 「流行りに」「乗って」처럼 자립어에 붙는 조사·어미까지 한 토큰입니다.
- 문장부호는 앞 문절에 붙입니다. 문장부호만 있는 토큰을 만들지 마세요.
- 토큰: w(원문 표기), kana(요미가나), pron(한글 발음). kana와 pron은 문절을 통째로 적습니다(글자별로 쪼개지 않습니다).
  예) { "w": "最近、", "kana": "さいきん、", "pron": "사이킨," }
- 숫자는 읽는 대로 풀어 적습니다.
  예) { "w": "2023年", "kana": "にせんにじゅうさんねん", "pron": "니센니쥬-산넨" }`,

      reading: `## 요미가나
- 한자의 읽는 법은 히라가나로 적습니다.
- 원문이 가타카나인 부분은 가타카나 그대로 둡니다(이미 읽는 법이므로).
- 문절에 붙은 조사·어미와 문장부호까지 그대로 포함해 적습니다.`,

      pron: `## 한글 발음
외래어 표기법이 아니라 **실제로 들리는 소리**에 가깝게 적습니다. 문절 통째로 적습니다.
- 장음은 \`-\`로 적습니다: 手帳 테쵸-, 東京 토-쿄-.
- 촉음은 받침으로 옮깁니다: 乗って 놋테, やっぱり 얍파리.
- ん은 받침으로 적습니다: 最近 사이킨, 日記帳 닛키쵸-.
- 예시 (한 문장 통째로):
  最近、流行りに乗って手帳にも興味が湧いてきたけど、やっぱり誰も見ない傷だらけの日記帳のほうが好きみたい。
  さいきん、はやりに のって てちょうにも きょうみが わいて きたけど、やっぱり だれも みない きずだらけの にっきちょうの ほうが すきみたい。
  사이킨, 하야리니 놋테 테쵸-니모 쿄-미가 와이테 키타케도, 얍파리 다레모 미나이 키즈다라케노 닛키쵸-노 호-가 스키미타이.`,

      glossExample: `예시 (한 문장을 네 줄로):
  最近、流行りに乗って              → "요즘 유행을 타서"
  手帳にも興味が湧いてきたけど、     → "다이어리에도 흥미가 생겼지만"
  やっぱり誰も見ない                → "그래도 아무도 안 보는"
  傷だらけの日記帳のほうが好きみたい。 → "상처투성이 일기장이 더 좋은 것 같아"`,

      notesReading: '히라가나 요미가나',
      highlightTitle: '〜てきた',
    },
  });
}
